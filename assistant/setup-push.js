// Creates the key pair for iPhone push notifications (Web Push / VAPID).
// The private key goes to your Keychain; the public key is written to
// approvals/push-config.js (public by design — it only identifies this sender).
//   node setup-push.js            create if missing
//   node setup-push.js --rotate   replace (phones must re-enable notifications)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import webpush from 'web-push';
import { getSecret, setSecret, SECRETS } from './lib/keychain.js';

const here = path.dirname(fileURLToPath(import.meta.url));
let keys = getSecret(SECRETS.vapid);
if (!keys || process.argv.includes('--rotate')) {
  keys = JSON.stringify(webpush.generateVAPIDKeys());
  setSecret(SECRETS.vapid, keys);
  console.log('Created new push keys (private key stored in Keychain).');
}
const { publicKey } = JSON.parse(keys);
const out = path.join(here, '..', 'approvals', 'push-config.js');
fs.writeFileSync(out, `// Generated by assistant/setup-push.js — public key only.\nself.VAPID_PUBLIC_KEY = '${publicKey}';\n`);
console.log('Wrote', path.relative(process.cwd(), out), '— commit it so the Approvals page can subscribe.');
